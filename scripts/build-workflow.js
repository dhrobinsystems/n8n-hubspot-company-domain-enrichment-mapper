function codeNode(name, entryKey, position, mode, notes) {
  const parameters = { jsCode: `${buildPreamble()}\n${ENTRIES[entryKey]}` };
  if (mode === 'each') parameters.mode = 'runOnceForEachItem';
  return { parameters, id: stableId(name), name, type: 'n8n-nodes-base.code', typeVersion: 2, position, notes };
}

function boolIf(name, expression, position) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' },
        conditions: [
          { id: stableId(`${name}-condition`), leftValue: expression, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } },
        ],
        combinator: 'and',
      },
      options: {},
    },
    id: stableId(name),
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2,
    position,
  };
}

